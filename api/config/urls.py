# POST/PUT/DELETE cannot survive an APPEND_SLASH redirect, so both spellings are served directly.
urlpatterns = [path("", api_home), path("admin/", admin.site.urls)]
for route in routes:
    urlpatterns += [route, path(f"{route.pattern}/", route.callback)]


# The panel and CLI only understand JSON; never return Django's HTML error page for API routes.
def _json_error(status: int, detail: str):
    def view(request, exception=None):
        from django.http import JsonResponse

        return JsonResponse({"detail": detail}, status=status)

    return view


handler404 = _json_error(404, "Not found")
handler500 = _json_error(500, "Internal server error; details are in the API log")
